"""Copy each stage prompt into the header of the file it generated. Idempotent."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "# === AI-GENERATED CODE: PROMPT RECORD START ==="
END = "# === AI-GENERATED CODE: PROMPT RECORD END ==="


def prompt_for(path):
    """Prompt file that generated this file, or None."""
    rel = path.relative_to(ROOT).as_posix()
    n = path.name
    if rel.startswith("src/") and n[:2].isdigit():
        hits = sorted((ROOT / "prompts").glob(n[:2] + "-*.md"))
        return hits[0] if hits else None
    if n == "report.py": return ROOT / "prompts" / "report.md"
    if n == "predict.py": return ROOT / "prompts" / "10-predict.md"
    if n == "common.py" or rel.startswith("tools/") or n == "Makefile": return ROOT / "prompts" / "setup.md"
    if rel.startswith("tests/"): return ROOT / "prompts" / "BUILD.md"
    return None


def targets():
    out = [ROOT / "Makefile"]
    for d in ("src", "tools", "tests"):
        out += sorted((ROOT / d).glob("*.py"))
    return [p for p in out if p.exists() and prompt_for(p)]


def block(path):
    parts = [("prompts/00-context.md", (ROOT / "prompts" / "00-context.md").read_text())]
    p = prompt_for(path)
    parts.append((p.relative_to(ROOT).as_posix(), p.read_text()))
    lines = [START, "# This file was generated by an AI assistant (Claude) from the prompts below, reproduced in full."]
    for name, txt in parts:
        lines.append(f"# --- {name} ---")
        lines += [("# " + l).rstrip() for l in txt.rstrip("\n").split("\n")]
    lines.append(END)
    return "\n".join(lines) + "\n"


def split(text):
    """(header block or '', rest)."""
    if text.startswith(START):
        i = text.index(END) + len(END)
        return text[:i].lstrip("\n") + "\n", text[i:].lstrip("\n")
    return "", text


def main():
    for p in targets():
        _, rest = split(p.read_text())
        p.write_text(block(p) + rest)
        print("stamped", p.relative_to(ROOT))


if __name__ == "__main__":
    sys.exit(main())
